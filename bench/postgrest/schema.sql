-- The parts of examples/bookstore.sql that the benchmark scenarios use, for
-- PostgreSQL + PostgREST. Types and constraints match the Firebird schema;
-- the computed field is a function taking the table row, as PostgREST wants.
--
--   psql -U postgres -d bench -f schema.sql

CREATE TABLE authors (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    varchar(100) NOT NULL,
  country varchar(60),
  born    date
);

CREATE TABLE books (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title     varchar(200) NOT NULL,
  author_id integer REFERENCES authors(id),
  price     numeric(10,2),
  published smallint,
  in_stock  boolean DEFAULT true NOT NULL,
  summary   text,
  added_at  timestamp DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tags (
  id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(40) NOT NULL UNIQUE
);

CREATE TABLE book_tags (
  book_id integer NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  tag_id  integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (book_id, tag_id)
);

CREATE TABLE customers (
  id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(120) NOT NULL UNIQUE,
  name  varchar(100)
);

CREATE TABLE orders (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id),
  created_at  timestamp DEFAULT CURRENT_TIMESTAMP,
  status      varchar(20) DEFAULT 'new' NOT NULL
);

CREATE TABLE order_items (
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  book_id  integer NOT NULL REFERENCES books(id),
  qty      integer DEFAULT 1 NOT NULL,
  PRIMARY KEY (order_id, book_id)
);

-- Firebird creates an index for every foreign key; PostgreSQL does not.
CREATE INDEX ON books (author_id);
CREATE INDEX ON book_tags (tag_id);
CREATE INDEX ON orders (customer_id);
CREATE INDEX ON order_items (book_id);

-- GET /rpc/add_vat?amount=100
CREATE FUNCTION add_vat (amount numeric, rate numeric DEFAULT 19) RETURNS numeric
LANGUAGE sql IMMUTABLE AS $$ SELECT amount * (100 + rate) / 100 $$;

-- computed field: GET /books?select=title,price_with_vat
CREATE FUNCTION price_with_vat (books) RETURNS numeric
LANGUAGE sql IMMUTABLE AS $$ SELECT $1.price * 1.19 $$;

