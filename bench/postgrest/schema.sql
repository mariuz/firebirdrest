-- roles as in the Firebird example: anonymous reads, users write
CREATE ROLE web_anon NOLOGIN;
CREATE ROLE web_user NOLOGIN;
CREATE ROLE authenticator LOGIN PASSWORD 'authenticator' NOINHERIT;
GRANT web_anon TO authenticator;
GRANT web_user TO authenticator;

GRANT USAGE ON SCHEMA public TO web_anon, web_user;
GRANT SELECT ON authors, books, tags, book_tags TO web_anon;
GRANT EXECUTE ON FUNCTION add_vat, price_with_vat TO web_anon;
GRANT ALL ON authors, books, tags, book_tags, customers, orders, order_items TO web_user;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO web_user;
GRANT EXECUTE ON FUNCTION add_vat, price_with_vat TO web_user;
