SET TERM ^ ;
-- the session time zone of the request: GET /rpc/session_zone (Prefer: timezone= changes it)
CREATE FUNCTION session_zone RETURNS VARCHAR(63)
AS
BEGIN
  RETURN RDB$GET_CONTEXT('SYSTEM', 'SESSION_TIMEZONE');
END^
SET TERM ; ^

GRANT SELECT ON meetings TO ROLE web_anon;
GRANT ALL ON meetings TO ROLE web_user;
GRANT EXECUTE ON FUNCTION session_zone TO ROLE web_anon;
GRANT EXECUTE ON FUNCTION session_zone TO ROLE web_user;
COMMIT;
