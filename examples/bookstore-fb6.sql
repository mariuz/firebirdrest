-- selectable procedure: GET /rpc/low_stock?below=5 with Accept-Profile: inventory
CREATE PROCEDURE inventory.low_stock (below INTEGER)
RETURNS (warehouse VARCHAR(60), book_id INTEGER, qty INTEGER)
AS
BEGIN
  FOR SELECT w.name, s.book_id, s.qty
      FROM inventory.stock s JOIN inventory.warehouses w ON w.id = s.warehouse_id
      WHERE s.qty < :below ORDER BY w.name, s.book_id
      INTO :warehouse, :book_id, :qty
  DO SUSPEND;
END^

CREATE PACKAGE inventory.reports AS
BEGIN
  FUNCTION total_qty (book_id INTEGER) RETURNS INTEGER;
END^

CREATE PACKAGE BODY inventory.reports AS
BEGIN
  FUNCTION total_qty (book_id INTEGER) RETURNS INTEGER AS
  BEGIN
    RETURN (SELECT COALESCE(SUM(qty), 0) FROM inventory.stock WHERE book_id = :book_id);
  END
END^
SET TERM ; ^

-- a schema needs USAGE in addition to the grants on its objects
GRANT USAGE ON SCHEMA inventory TO ROLE web_anon;
GRANT USAGE ON SCHEMA inventory TO ROLE web_user;
GRANT SELECT ON inventory.warehouses TO ROLE web_anon;
GRANT SELECT ON inventory.books TO ROLE web_anon;
GRANT SELECT ON inventory.stock TO ROLE web_anon;
GRANT ALL ON inventory.warehouses TO ROLE web_user;
GRANT ALL ON inventory.books TO ROLE web_user;
GRANT ALL ON inventory.stock TO ROLE web_user;
GRANT EXECUTE ON PROCEDURE inventory.low_stock TO ROLE web_anon;
GRANT EXECUTE ON PACKAGE inventory.reports TO ROLE web_anon;
GRANT EXECUTE ON PROCEDURE inventory.low_stock TO ROLE web_user;
GRANT EXECUTE ON PACKAGE inventory.reports TO ROLE web_user;
GRANT SELECT ON inventory.stock TO PROCEDURE inventory.low_stock;
GRANT SELECT ON inventory.warehouses TO PROCEDURE inventory.low_stock;
GRANT SELECT ON inventory.stock TO PACKAGE inventory.reports;
COMMIT;
