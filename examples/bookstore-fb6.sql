-- Additions to bookstore.sql for Firebird 6 and later: a second SQL schema.
-- Expose it with db-schemas = "public, inventory" and select it per request
-- with Accept-Profile: inventory (reads) or Content-Profile: inventory (writes).

CREATE SCHEMA inventory;
COMMIT;

CREATE TABLE inventory.warehouses (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(60) NOT NULL
);

-- a table with the same name as PUBLIC.BOOKS: each schema has its own
CREATE TABLE inventory.books (
  sku   VARCHAR(20) NOT NULL PRIMARY KEY,
  title VARCHAR(200) NOT NULL
);

CREATE TABLE inventory.stock (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id INTEGER NOT NULL REFERENCES inventory.warehouses(id),
  book_id      INTEGER NOT NULL REFERENCES public.books(id),  -- crosses schemas: not embeddable
  qty          INTEGER DEFAULT 0 NOT NULL
);

