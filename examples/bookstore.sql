/*
 * Example database for FirebirdREST.
 *
 * Run as SYSDBA (or the database owner):
 *   isql -user SYSDBA -password masterkey localhost:/var/lib/firebird/data/test.fdb -i bookstore.sql
 *
 * The API connects as the user AUTHENTICATOR, which has no privileges of its
 * own (do not use the database owner or SYSDBA: they bypass all grants). Requests switch to role WEB_ANON (no token) or to the role named in
 * the JWT "role" claim, e.g. WEB_USER.
 */
SET SQL DIALECT 3;
SET AUTODDL ON;

CREATE TABLE authors (
  id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    VARCHAR(100) NOT NULL,
  country VARCHAR(60),
  born    DATE
);

CREATE TABLE books (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title     VARCHAR(200) NOT NULL,
  author_id INTEGER REFERENCES authors(id),
  price     NUMERIC(10,2),
  published SMALLINT,
  in_stock  BOOLEAN DEFAULT TRUE NOT NULL,
  summary   BLOB SUB_TYPE TEXT,
  added_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tags (
  id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(40) NOT NULL UNIQUE
);

-- junction table: books <-> tags (many-to-many)
CREATE TABLE book_tags (
  book_id INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  tag_id  INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (book_id, tag_id)
);

CREATE TABLE customers (
  id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(120) NOT NULL UNIQUE,
  name  VARCHAR(100)
);

CREATE TABLE orders (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id),
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  status      VARCHAR(20) DEFAULT 'new' NOT NULL
);

CREATE TABLE order_items (
  order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  book_id  INTEGER NOT NULL REFERENCES books(id),
  qty      INTEGER DEFAULT 1 NOT NULL,
  PRIMARY KEY (order_id, book_id)
);

CREATE VIEW books_with_authors AS
  SELECT b.id, b.title, a.name AS author, b.price
  FROM books b LEFT JOIN authors a ON a.id = b.author_id;

SET TERM ^ ;

-- selectable procedure: GET /rpc/books_by_country?country=UK
CREATE PROCEDURE books_by_country (country VARCHAR(60))
RETURNS (title VARCHAR(200), author VARCHAR(100), price NUMERIC(10,2))
AS
BEGIN
  FOR SELECT b.title, a.name, b.price
      FROM books b JOIN authors a ON a.id = b.author_id
      WHERE a.country = :country
      INTO :title, :author, :price
  DO SUSPEND;
END^

-- executable procedure: POST /rpc/place_order {"customer_id":1,"book_id":2,"qty":1}
CREATE PROCEDURE place_order (customer_id INTEGER, book_id INTEGER, qty INTEGER = 1)
RETURNS (order_id INTEGER)
AS
BEGIN
  INSERT INTO orders (customer_id) VALUES (:customer_id) RETURNING id INTO :order_id;
  INSERT INTO order_items (order_id, book_id, qty) VALUES (:order_id, :book_id, :qty);
END^

-- function: GET /rpc/add_vat?amount=100
CREATE FUNCTION add_vat (amount NUMERIC(10,2), rate NUMERIC(5,2) = 19)
RETURNS NUMERIC(12,2)
AS
BEGIN
  RETURN amount * (100 + rate) / 100;
END^

-- reads JWT claims that FirebirdREST puts in the transaction context
CREATE FUNCTION whoami
RETURNS VARCHAR(255)
AS
BEGIN
  RETURN COALESCE(RDB$GET_CONTEXT('USER_TRANSACTION', 'request.jwt.claim.sub'), 'anonymous')
         || ' as ' || CURRENT_ROLE;
END^

/*
 * Computed relationships and fields: routines whose input parameters are all
 * declared TYPE OF COLUMN <table>.<column> can be embedded in that table.
 */

-- to-many: GET /books?select=title,similar_books(title)
CREATE PROCEDURE similar_books (book_id TYPE OF COLUMN books.id, author_id TYPE OF COLUMN books.author_id)
RETURNS (id INTEGER, title VARCHAR(200))
AS
BEGIN
  FOR SELECT b.id, b.title FROM books b
      WHERE b.author_id = :author_id AND b.id <> :book_id
      ORDER BY b.id
      INTO :id, :title
  DO SUSPEND;
END^

-- to-one (executable procedure): GET /authors?select=name,author_stats(*)
CREATE PROCEDURE author_stats (author_id TYPE OF COLUMN authors.id)
RETURNS (book_count INTEGER, avg_price NUMERIC(10,2))
AS
BEGIN
  SELECT COUNT(*), AVG(b.price) FROM books b WHERE b.author_id = :author_id
    INTO :book_count, :avg_price;
END^

-- computed fields: GET /books?select=title,price_with_vat&price_with_vat=gt.10
CREATE FUNCTION price_with_vat (price TYPE OF COLUMN books.price)
RETURNS NUMERIC(12,2)
AS
BEGIN
  RETURN price * 1.19;
END^

CREATE FUNCTION label (title TYPE OF COLUMN books.title, published TYPE OF COLUMN books.published)
RETURNS VARCHAR(220)
AS
BEGIN
  RETURN title || ' (' || published || ')';
END^

-- package: GET /rpc/catalog.search?term=god , GET /rpc/catalog.book_count?author_id=1
CREATE PACKAGE catalog AS
BEGIN
  PROCEDURE search (term VARCHAR(100)) RETURNS (id INTEGER, title VARCHAR(200));
  FUNCTION book_count (author_id INTEGER) RETURNS INTEGER;
END^

CREATE PACKAGE BODY catalog AS
BEGIN
  PROCEDURE search (term VARCHAR(100)) RETURNS (id INTEGER, title VARCHAR(200))
  AS
  BEGIN
    FOR SELECT b.id, b.title FROM books b WHERE b.title CONTAINING :term
        INTO :id, :title
    DO SUSPEND;
  END

  FUNCTION book_count (author_id INTEGER) RETURNS INTEGER
  AS
  BEGIN
    RETURN (SELECT COUNT(*) FROM books b WHERE b.author_id = :author_id);
  END

  -- not declared in the package header: private, so not exposed by the API
  FUNCTION internal_helper RETURNS INTEGER
  AS
  BEGIN
    RETURN 42;
  END
END^

